export type Messages = typeof EN;

interface LanguageDefinition {
  /** Stable code, also the value stored in localStorage. */
  code: string;
  /** Compact label for the header button. */
  short: string;
  /** Native name shown in the language menu. */
  label: string;
  /** Locale used by Intl for dates and numbers. */
  locale: string;
  messages: Messages;
}

/**
 * To add a language: copy `EN` into a new object with the same keys, then add one entry here.
 * `satisfies` makes TypeScript reject missing or extra message keys, and `Lang` follows the
 * registry automatically.
 */
export const LANGUAGES = [
  { code: 'en', short: 'EN', label: 'English', locale: 'en-GB', messages: EN },
  { code: 'ru', short: 'RU', label: 'Русский', locale: 'ru-RU', messages: RU },
] as const satisfies readonly LanguageDefinition[];

export type Lang = (typeof LANGUAGES)[number]['code'];

export const DEFAULT_LANG: Lang = LANGUAGES[0].code;

const STORAGE_KEY = 'boorushiko.lang';

function isLang(value: string | null): value is Lang {
  return value !== null && LANGUAGES.some((language) => language.code === value);
}

function initialLang(): Lang {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (isLang(stored)) return stored;
  } catch {
    // Storage can be unavailable in private mode; the gallery still opens in English.
  }
  // English is the default audience; a saved manual choice wins above.
  return DEFAULT_LANG;
}

@Injectable({ providedIn: 'root' })
export class I18n {
  private readonly document = inject(DOCUMENT);
  readonly lang = signal<Lang>(initialLang());
  readonly languages = LANGUAGES;
  readonly currentLanguage = computed(
    () => LANGUAGES.find((language) => language.code === this.lang()) ?? LANGUAGES[0],
  );
  readonly locale = computed(() => this.currentLanguage().locale);
  readonly t = computed<Messages>(() => this.currentLanguage().messages);

  constructor() {
    effect(() => {
      this.document.documentElement.lang = this.lang();
    });
  }

  setLang(lang: Lang): void {
    this.lang.set(lang);
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      // Persisting the choice is best-effort.
    }
  }
}
